/* ── Get News Functions ───────────────────────────────────────────── */
export function getNews(): NewsArticle[] {
  return NEWS_DATA.filter((n) => n.status === "published").sort((a, b) => 
    new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
  );
}

export function getNewsBySlug(slug: string): NewsArticle | undefined {
  return NEWS_DATA.find((n) => n.slug === slug && n.status === "published");
}

export function getFeaturedNews(): NewsArticle[] {
  return NEWS_DATA.filter((n) => n.featured && n.status === "published").sort((a, b) => 
    new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
  );
}

export function getNewsByCategory(categoryKey: string): NewsArticle[] {
  if (categoryKey === "all") return getNews();
  return NEWS_DATA.filter((n) => n.categoryKey === categoryKey && n.status === "published").sort((a, b) => 
    new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
  );
}

export function getLatestNews(limit: number = 3): NewsArticle[] {
  return getNews().slice(0, limit);
}
